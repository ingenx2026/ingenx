const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { compileStrapi, createStrapi } = require('@strapi/strapi');
process.env.DATABASE_CLIENT = 'sqlite';
process.env.DATABASE_FILENAME = `.tmp/volunteer-test-${process.pid}.db`;
process.env.PORT = '1440'; process.env.HOST = '127.0.0.1'; process.env.NODE_ENV = 'test';
let app;
(async () => {
  const context = await compileStrapi();
  app = await createStrapi({ ...context, serveAdminPanel: false }).start();
  const url = 'http://127.0.0.1:1440/api/volunteer-registration';
  const terms = await fetch(url).then(r => r.json());
  assert.equal(terms.statements.length, 3);
  const post = body => fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const body = { name: 'Test Volunteer', email: 'Volunteer@example.com', location: 'Delhi', agreements: [true, true, true], consentVersion: terms.version, requestId: randomUUID() };
  assert.equal((await post({ ...body, agreements: [true, false, true] })).status, 400);
  assert.equal((await post({ ...body, email: 'invalid' })).status, 400);
  assert.equal((await post({ ...body, location: '' })).status, 400);
  assert.equal((await post({ ...body, consentVersion: 'old' })).status, 409);
  const response = await post(body); assert.equal(response.status, 201);
  const receipt = await response.json(); assert.ok(receipt.reference.startsWith('VOL-'));
  assert.deepEqual(Object.keys(receipt), ['reference']);
  assert.deepEqual(await (await post(body)).json(), receipt);
  assert.equal((await post({ ...body, name: 'Changed name' })).status, 409);
  const rows = await app.db.query('api::volunteer.volunteer').findMany();
  assert.equal(rows.length, 1); assert.equal(rows[0].email, 'volunteer@example.com');
  assert.deepEqual(rows[0].acknowledgements, terms.statements); assert.ok(rows[0].consentAt);
  assert.equal((await fetch('http://127.0.0.1:1440/api/volunteers')).status, 404);
  assert.equal((await post({ ...body, website: 'bot' })).status, 400);
  assert.equal((await post(body)).status, 429);
  console.log('PASS: required acknowledgements, validation, consent snapshot, persistence, idempotency, private responses, blocked public collection access and rate limits.');
  await app.destroy(); app = null;
})().catch(async error => { console.error(error); if (app) await app.destroy(); process.exitCode = 1; });
